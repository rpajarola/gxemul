#!/usr/bin/env python3
#
#  Generates the Alpha instruction tests (assembly source plus a list of
#  test-case descriptions, one per result line).
#
#  Each test case loads its operands from a table, executes one
#  instruction and stores the result quadword(s) into a result array,
#  which is printed in hex at the end. The output of a run is compared
#  line by line against reference output (made with QEMU's EV4 model, see
#  make_expected.sh), and the .list file says which test case a line
#  belongs to.
#
#  Only cases that cannot trap are generated: trapping behaviour depends
#  on PALcode and on the operating system's software completion, so it is
#  tested separately.
#
#  Usage: gen_tests.py outdir

import os
import random
import struct
import sys

MASK64 = (1 << 64) - 1


def sext(x, bits):
    x &= (1 << bits) - 1
    return x - (1 << bits) if x >> (bits - 1) else x


class Gen:
    """Collects the code, data and descriptions for one test program."""

    def __init__(self, name):
        self.name = name
        self.code = []
        self.data = []
        self.desc = []
        self.nvec = 0

    def vec(self, values):
        label = 'v%d' % self.nvec
        self.nvec += 1
        self.data.append('%s:\t.quad\t%s' % (
            label, ', '.join('0x%016x' % (v & MASK64) for v in values)))
        return label

    def result(self, reg, desc, fp=False):
        """Store register reg into the result array."""
        self.code.append('\t%s\t%s, 0($9)' % ('stt' if fp else 'stq', reg))
        self.code.append('\tlda\t$9, 8($9)')
        self.desc.append(desc)

    def write(self, outdir):
        with open(os.path.join(outdir, self.name + '.S'), 'w') as f:
            f.write('/*  Generated by gen_tests.py, do not edit.  */\n\n')
            f.write('\t.set\tnoreorder\n\t.set\tnoat\n\t.text\n')
            f.write('\t.globl\ttest_main\n\t.ent\ttest_main\n')
            f.write('test_main:\n')
            f.write('\tlda\t$30, -16($30)\n\tstq\t$26, 0($30)\n')
            f.write('\tstq\t$9, 8($30)\n')
            f.write('\tlda\t$9, results\n')
            for line in self.code:
                f.write(line + '\n')
            f.write('\tlda\t$16, results\n')
            f.write('\tsubq\t$9, $16, $17\n\tsrl\t$17, 3, $17\n')
            f.write('\tbsr\t$26, print_results\n')
            f.write('\tldq\t$26, 0($30)\n\tldq\t$9, 8($30)\n')
            f.write('\tlda\t$30, 16($30)\n')
            f.write('\tret\t$31, ($26), 1\n\t.end\ttest_main\n\n')
            f.write('\t.data\n\t.align\t3\n')
            for line in self.data:
                f.write(line + '\n')
            f.write('\n\t.bss\n\t.align\t3\nresults:\t.space\t%d\n' %
                    (8 * len(self.desc)))
        with open(os.path.join(outdir, self.name + '.list'), 'w') as f:
            for d in self.desc:
                f.write(d + '\n')


