#  Integer tests

EDGE = [0, 1, 2, 0x7f, 0x80, 0xff, 0x100, 0x7fff, 0x8000, 0xffff,
        0x7fffffff, 0x80000000, 0xffffffff, 0x100000000,
        0x7fffffffffffffff, 0x8000000000000000, MASK64, MASK64 - 1,
        0x0123456789abcdef, 0xfedcba9876543210, 0x00ff00ff00ff00ff,
        0x8080808080808080, 0x7f7f7f7f7f7f7f7f]


def int_values(rng, n):
    vals = list(EDGE)
    for _ in range(n):
        kind = rng.randrange(4)
        if kind == 0:
            vals.append(rng.getrandbits(64))
        elif kind == 1:
            vals.append(sext(rng.getrandbits(32), 32) & MASK64)
        elif kind == 2:
            vals.append(rng.getrandbits(rng.randrange(1, 64)))
        else:
            vals.append(rng.choice(EDGE) ^ (1 << rng.randrange(64)))
    return vals


def pairs(rng, vals, n):
    out = []
    for a in EDGE[:12]:
        for b in EDGE[:12]:
            out.append((a, b))
    for _ in range(n):
        out.append((rng.choice(vals), rng.choice(vals)))
    return out


#  Overflow predicates for the /V forms (cases that would trap are skipped).
def ovf_addl(a, b): return sext(a, 32) + sext(b, 32) != sext(a + b, 32)
def ovf_subl(a, b): return sext(a, 32) - sext(b, 32) != sext(a - b, 32)
def ovf_addq(a, b): return sext(a, 64) + sext(b, 64) != sext(a + b, 64)
def ovf_subq(a, b): return sext(a, 64) - sext(b, 64) != sext(a - b, 64)
def ovf_mull(a, b): return sext(a, 32) * sext(b, 32) != sext(a * b, 32)
def ovf_mulq(a, b): return sext(a, 64) * sext(b, 64) != sext(a * b, 64)


