CMOV_SENTINEL = 0x5555aaaa5555aaaa


def gen_int(name, ops, rng):
    g = Gen(name)
    vals = int_values(rng, 60)
    for mnem, ovf in ops:
        is_cmov = mnem.startswith('cmov')
        cases = pairs(rng, vals, 60)
        for a, b in cases:
            if ovf and ovf(a, b):
                continue
            v = g.vec([a, b])
            g.code.append('\tlda\t$1, %s' % v)
            g.code.append('\tldq\t$2, 0($1)')
            g.code.append('\tldq\t$3, 8($1)')
            if is_cmov:
                g.code.append('\tlda\t$1, %s' % g.vec([CMOV_SENTINEL]))
                g.code.append('\tldq\t$4, 0($1)')
            g.code.append('\t%s\t$2, $3, $4' % mnem)
            g.result('$4', '%s 0x%016x,0x%016x' % (mnem, a, b))
        #  Literal forms:
        for _ in range(12):
            a = rng.choice(vals)
            lit = rng.choice([0, 1, 7, 8, 31, 32, 63, 64, 127, 128, 255,
                              rng.randrange(256)])
            if ovf and ovf(a, lit):
                continue
            v = g.vec([a])
            g.code.append('\tlda\t$1, %s' % v)
            g.code.append('\tldq\t$2, 0($1)')
            if is_cmov:
                g.code.append('\tlda\t$1, %s' % g.vec([CMOV_SENTINEL]))
                g.code.append('\tldq\t$4, 0($1)')
            g.code.append('\t%s\t$2, %d, $4' % (mnem, lit))
            g.result('$4', '%s 0x%016x,#%d' % (mnem, a, lit))
        #  $31 as destination must stay zero:
        a, b = rng.choice(vals), rng.choice(vals)
        if not (ovf and ovf(a, b)):
            v = g.vec([a, b])
            g.code.append('\tlda\t$1, %s' % v)
            g.code.append('\tldq\t$2, 0($1)')
            g.code.append('\tldq\t$3, 8($1)')
            g.code.append('\t%s\t$2, $3, $31' % mnem)
            g.result('$31', '%s 0x%016x,0x%016x -> $31' % (mnem, a, b))
        #  Register $31 as source operands:
        a = rng.choice(vals)
        v = g.vec([a])
        g.code.append('\tlda\t$1, %s' % v)
        g.code.append('\tldq\t$2, 0($1)')
        if is_cmov:
            g.code.append('\tlda\t$1, %s' % g.vec([CMOV_SENTINEL]))
            g.code.append('\tldq\t$4, 0($1)')
        g.code.append('\t%s\t$31, $2, $4' % mnem)
        g.result('$4', '%s $31,0x%016x' % (mnem, a))
        if not (ovf and ovf(a, 0)):
            if is_cmov:
                g.code.append('\tldq\t$4, 0($1)')
            g.code.append('\t%s\t$2, $31, $4' % mnem)
            g.result('$4', '%s 0x%016x,$31' % (mnem, a))
    return g


def gen_int_misc(rng):
    """lda/ldah, ldq_u/stq_u, ll/sc, loads and stores, rc/rs, branches."""
    g = Gen('int_misc')
    vals = int_values(rng, 20)

    #  lda/ldah with various displacements:
    for a in vals[:30]:
        v = g.vec([a])
        g.code.append('\tlda\t$1, %s' % v)
        g.code.append('\tldq\t$2, 0($1)')
        for disp in (0, 1, -1, 0x7fff, -0x8000):
            g.code.append('\tlda\t$4, %d($2)' % disp)
            g.result('$4', 'lda %d(0x%016x)' % (disp, a))
            g.code.append('\tldah\t$4, %d($2)' % disp)
            g.result('$4', 'ldah %d(0x%016x)' % (disp, a))

    #  Loads of all sizes and alignments from a known buffer:
    buf = [rng.getrandbits(64) for _ in range(4)]
    bv = g.vec(buf)
    for off in range(0, 24, 4):
        g.code.append('\tlda\t$1, %s' % bv)
        g.code.append('\tldl\t$4, %d($1)' % off)
        g.result('$4', 'ldl +%d' % off)
    for off in range(0, 24, 8):
        g.code.append('\tldq\t$4, %d($1)' % off)
        g.result('$4', 'ldq +%d' % off)
    for off in range(0, 24, 3):
        g.code.append('\tldq_u\t$4, %d($1)' % off)
        g.result('$4', 'ldq_u +%d' % off)

    #  Stores, read back as quadwords:
    for i, (mnem, off) in enumerate([('stl', 0), ('stl', 4), ('stq', 8),
                                     ('stq_u', 19), ('stl', 28)]):
        sv = g.vec([0x1111111111111111 * (i + 1)] * 4)
        g.code.append('\tlda\t$1, %s' % sv)
        g.code.append('\tlda\t$2, %s' % g.vec([rng.getrandbits(64)]))
        g.code.append('\tldq\t$2, 0($2)')
        g.code.append('\t%s\t$2, %d($1)' % (mnem, off))
        for q in range(4):
            g.code.append('\tldq\t$4, %d($1)' % (q * 8))
            g.result('$4', '%s +%d -> quad %d' % (mnem, off, q))

    #  Unaligned byte store sequence (the way EV4 code stores bytes):
    for off in range(0, 16, 3):
        sv = g.vec([0x0123456789abcdef, 0xfedcba9876543210])
        g.code.append('\tlda\t$1, %s' % sv)
        g.code.append('\tlda\t$5, %d($1)' % off)
        g.code.append('\tlda\t$2, 0xa5($31)')
        g.code.append('\tldq_u\t$3, 0($5)')
        g.code.append('\tinsbl\t$2, $5, $6')
        g.code.append('\tmskbl\t$3, $5, $3')
        g.code.append('\tbis\t$3, $6, $3')
        g.code.append('\tstq_u\t$3, 0($5)')
        for q in range(2):
            g.code.append('\tldq\t$4, %d($1)' % (q * 8))
            g.result('$4', 'byte store +%d -> quad %d' % (off, q))

    #  Load-locked / store-conditional, uninterrupted sequence succeeds:
    for mnem_l, mnem_c in (('ldl_l', 'stl_c'), ('ldq_l', 'stq_c')):
        sv = g.vec([0x8000000180000001, 0x7777777777777777])
        g.code.append('\tlda\t$1, %s' % sv)
        g.code.append('\t%s\t$4, 0($1)' % mnem_l)
        g.result('$4', '%s' % mnem_l)
        g.code.append('\taddq\t$4, 1, $4')
        g.code.append('\t%s\t$4, 0($1)' % mnem_c)
        g.result('$4', '%s status' % mnem_c)
        g.code.append('\tldq\t$4, 0($1)')
        g.result('$4', '%s memory' % mnem_c)

    #  Branches: record which way each one went.
    for mnem in ('beq', 'bne', 'blt', 'bge', 'ble', 'bgt', 'blbc', 'blbs'):
        for a in (0, 1, 2, MASK64, 0x8000000000000000, 0x7fffffffffffffff,
                  0x100000000):
            v = g.vec([a])
            n = len(g.desc)
            g.code.append('\tlda\t$1, %s' % v)
            g.code.append('\tldq\t$2, 0($1)')
            g.code.append('\tlda\t$4, 1($31)')
            g.code.append('\t%s\t$2, b%d' % (mnem, n))
            g.code.append('\tlda\t$4, 0($31)')
            g.code.append('b%d:' % n)
            g.result('$4', '%s 0x%016x taken' % (mnem, a))

    #  bsr/br/jsr/ret return addresses (relative to a label):
    g.code.append('\tbr\t$4, br1')
    g.code.append('br1:\tlda\t$5, br1')
    g.code.append('\tsubq\t$4, $5, $4')
    g.result('$4', 'br return address - label')
    g.code.append('\tlda\t$5, jt1')
    g.code.append('\tjsr\t$4, ($5)')
    g.code.append('jr1:\tbr\tjt2')
    g.code.append('jt1:\tlda\t$6, jr1')
    g.code.append('\tsubq\t$4, $6, $4')
    g.code.append('jt2:')
    g.result('$4', 'jsr return address - label')

    #  RC/RS: read and clear/set the per-processor intr_flag.
    g.code.append('\trs\t$4')
    g.code.append('\trs\t$4')
    g.result('$4', 'rs after rs')
    g.code.append('\trc\t$4')
    g.result('$4', 'rc after rs')
    g.code.append('\trc\t$4')
    g.result('$4', 'rc after rc')

    #  Instructions that must do nothing visible here:
    g.code.append('\tlda\t$4, 0x1234($31)')
    for ins in ('trapb', 'excb', 'mb', 'wmb', 'fetch ($1)',
                'fetch_m ($1)'):
        g.code.append('\t' + ins)
    g.result('$4', 'barriers and hints')
    return g


