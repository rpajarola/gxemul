#  Floating point tests (IEEE S/T and VAX F/G, non-trapping cases only)

def t_bits(x):
    return struct.unpack('<Q', struct.pack('<d', x))[0]


def s_reg_bits(x):
    """S-format value as held in a register: the T-format of the float."""
    f = struct.unpack('<f', struct.pack('<f', x))[0]
    return t_bits(f)


def fp_values(rng, single):
    """Finite, normal values whose results are unlikely to over/underflow."""
    vals = [1.0, -1.0, 2.0, 0.5, 3.0, 10.0, 0.1, -0.1, 1e10, -1e10,
            1.0 / 3, 2.0 / 3, 123456.789, -98765.4321, 1e-5, 0.0, -0.0,
            1.5, 1.0 + 2 ** -23, 1.0 + 2 ** -52, 4096.0, 65535.0,
            16777215.0, 16777217.0]
    for _ in range(40):
        m = rng.uniform(1.0, 2.0)
        e = rng.randrange(-20, 21)
        v = m * 2.0 ** e
        if rng.randrange(2):
            v = -v
        vals.append(v)
    conv = s_reg_bits if single else t_bits
    return [conv(v) for v in vals]


IEEE_RND = ['', '/c', '/m', '/d']
IEEE_TRP = ['', '/u', '/su']      #  /sui traps on inexact: not here.


def fp_prologue(g, fpcr):
    """Load FPCR (e.g. dynamic rounding mode) from a vector."""
    g.code.append('\tlda\t$1, %s' % g.vec([fpcr]))
    g.code.append('\tldt\t$f10, 0($1)')
    g.code.append('\tmt_fpcr\t$f10')
    g.code.append('\texcb')


FPCR_DYN = {0: 0 << 58, 1: 1 << 58, 2: 2 << 58, 3: 3 << 58}
DYN_NAMES = ['chopped', 'minus', 'normal', 'plus']


def inf_rounding(rnd, dyn):
    """Rounding towards +/- infinity: the 21064 leaves it to software
    (FEN exception), so these cases go to separate tests (NAME_inf) that
    run on a 21164."""
    return rnd == '/m' or (rnd == '/d' and dyn in (1, 3))


def gen_fp_ieee(rng):
    g0 = Gen('fp_ieee')
    g0.inf = Gen('fp_ieee_inf')
    for fmt, single in (('s', True), ('t', False)):
        vals = fp_values(rng, single)
        for fn in ('add', 'sub', 'mul', 'div'):
            for rnd in IEEE_RND:
                for trp in IEEE_TRP:
                    dyns = range(4) if rnd == '/d' else [2]
                    for dyn in dyns:
                        g = g0.inf if inf_rounding(rnd, dyn) else g0
                        fp_prologue(g, FPCR_DYN[dyn])
                        mnem = '%s%s%s' % (fn, fmt,
                                           (trp + rnd[1:] if trp
                                            else rnd))
                        for _ in range(10):
                            a = rng.choice(vals)
                            b = rng.choice(vals)
                            if fn == 'div' and (b & ~(1 << 63)) == 0:
                                continue
                            v = g.vec([a, b])
                            g.code.append('\tlda\t$1, %s' % v)
                            g.code.append('\tldt\t$f1, 0($1)')
                            g.code.append('\tldt\t$f2, 8($1)')
                            g.code.append('\t%s\t$f1, $f2, $f3' % mnem)
                            g.result('$f3', '%s[%s] %016x,%016x' % (
                                mnem, DYN_NAMES[dyn], a, b), fp=True)
        g0.code.append('\ttrapb')
    g = g0
    #  Results that underflow are a true zero without /U (the 21064
    #  doesn't make denormals); with /U they would trap.
    tiny_t = [t_bits(x) for x in (1e-200, -1e-200, 3e-160, 2.0 ** -600)]
    tiny_s = [s_reg_bits(x) for x in (1e-25, -1e-25, 3e-20, 2.0 ** -70)]
    fp_prologue(g, FPCR_DYN[2])
    for fmt, tiny in (('s', tiny_s), ('t', tiny_t)):
        for mnem in ('mul' + fmt, 'mul%s/c' % fmt, 'mul%s/m' % fmt,
                     'div%s' % fmt):
            g = g0.inf if mnem.endswith('/m') else g0
            if g is g0.inf:
                fp_prologue(g, FPCR_DYN[2])
            for a in tiny:
                for b in tiny:
                    if mnem.startswith('div'):
                        b = t_bits(1e200) if fmt == 't' else s_reg_bits(1e30)
                    v = g.vec([a, b])
                    g.code.append('\tlda\t$1, %s' % v)
                    g.code.append('\tldt\t$f1, 0($1)')
                    g.code.append('\tldt\t$f2, 8($1)')
                    g.code.append('\t%s\t$f1, $f2, $f3' % mnem)
                    g.result('$f3', '%s[normal] %016x,%016x' % (mnem, a, b),
                             fp=True)
    g = g0
    #  Compares (T only; /su needed for unordered on real hardware, but
    #  with non-NaN inputs plain compares never trap):
    vals = fp_values(rng, False)
    fp_prologue(g, FPCR_DYN[2])
    for mnem in ('cmpteq', 'cmptlt', 'cmptle', 'cmptun',
                 'cmpteq/su', 'cmptlt/su', 'cmptle/su', 'cmptun/su'):
        for _ in range(16):
            a = rng.choice(vals)
            b = rng.choice(vals + [a])
            v = g.vec([a, b])
            g.code.append('\tlda\t$1, %s' % v)
            g.code.append('\tldt\t$f1, 0($1)')
            g.code.append('\tldt\t$f2, 8($1)')
            g.code.append('\t%s\t$f1, $f2, $f3' % mnem)
            g.result('$f3', '%s %016x,%016x' % (mnem, a, b), fp=True)
    g.code.append('\ttrapb')
    return g


def gen_fp_conv(rng):
    g0 = g = Gen('fp_conv')
    g0.inf = Gen('fp_conv_inf')
    ints = [0, 1, MASK64, 2, 3, 100, 0x7fffffff, 0x80000000, 0xffffffff,
            1 << 52, (1 << 53) + 1, (1 << 24) + 1, 0x7fffffffffffffff,
            0x8000000000000000, 0x0123456789abcdef]
    ints += [rng.getrandbits(rng.randrange(1, 64)) for _ in range(20)]
    ints += [(-rng.getrandbits(rng.randrange(1, 63))) & MASK64
             for _ in range(10)]
    for dst in ('s', 't'):
        for rnd in IEEE_RND:
            dyns = range(4) if rnd == '/d' else [2]
            for trp in ('', '/sui'):
                if trp == '/sui':
                    continue        #  Inexact would trap.
                for dyn in dyns:
                    g = g0.inf if inf_rounding(rnd, dyn) else g0
                    fp_prologue(g, FPCR_DYN[dyn])
                    mnem = 'cvtq%s%s' % (dst, rnd)
                    for q in ints:
                        v = g.vec([q])
                        g.code.append('\tlda\t$1, %s' % v)
                        g.code.append('\tldt\t$f1, 0($1)')
                        g.code.append('\t%s\t$f1, $f3' % mnem)
                        g.result('$f3', '%s[%s] %016x' % (
                            mnem, DYN_NAMES[dyn], q), fp=True)
    #  cvttq: in-range values only (/v would trap on overflow).
    tv = [t_bits(x) for x in (0.0, -0.0, 0.5, 1.5, 2.5, -0.5, -1.5, -2.5,
                              1.0, 1e15, -1e15, 2.0 ** 62, -(2.0 ** 63),
                              123.456, -123.456, 0.9999, -0.9999, 1e-10)]
    tv += [t_bits(rng.uniform(-1e12, 1e12)) for _ in range(20)]
    for rnd in IEEE_RND:
        for trp in ('', '/v', '/sv'):
            dyns = range(4) if rnd == '/d' else [2]
            for dyn in dyns:
                g = g0.inf if inf_rounding(rnd, dyn) else g0
                fp_prologue(g, FPCR_DYN[dyn])
                mnem = 'cvttq%s%s' % (trp, rnd[1:] if trp else rnd)
                for t in tv:
                    v = g.vec([t])
                    g.code.append('\tlda\t$1, %s' % v)
                    g.code.append('\tldt\t$f1, 0($1)')
                    g.code.append('\t%s\t$f1, $f3' % mnem)
                    g.result('$f3', '%s[%s] %016x' % (
                        mnem, DYN_NAMES[dyn], t), fp=True)
    #  cvtts (T -> S rounding), in range:
    tv2 = [t_bits(rng.uniform(-1e6, 1e6)) for _ in range(20)]
    tv2 += [t_bits(1.0 + 2 ** -24), t_bits(1.0 + 3 * 2 ** -24),
            t_bits(-(1.0 + 2 ** -24)), t_bits(1.0 + 2 ** -25)]
    for rnd in IEEE_RND:
        for trp in ('', '/u', '/su'):
            dyns = range(4) if rnd == '/d' else [2]
            for dyn in dyns:
                g = g0.inf if inf_rounding(rnd, dyn) else g0
                fp_prologue(g, FPCR_DYN[dyn])
                mnem = 'cvtts%s%s' % (trp, rnd[1:] if trp else rnd)
                for t in tv2:
                    v = g.vec([t])
                    g.code.append('\tlda\t$1, %s' % v)
                    g.code.append('\tldt\t$f1, 0($1)')
                    g.code.append('\t%s\t$f1, $f3' % mnem)
                    g.result('$f3', '%s[%s] %016x' % (
                        mnem, DYN_NAMES[dyn], t), fp=True)
    g = g0
    #  cvtst (S -> T, exact):
    fp_prologue(g, FPCR_DYN[2])
    for x in (0.0, -0.0, 1.0, -2.5, 1e30, 3.4e38, 1e-30):
        sb = s_reg_bits(x)
        v = g.vec([sb])
        g.code.append('\tlda\t$1, %s' % v)
        g.code.append('\tldt\t$f1, 0($1)')
        g.code.append('\tcvtst/s\t$f1, $f3')
        g.result('$f3', 'cvtst/s %016x' % sb, fp=True)
    #  cvtlq / cvtql (longword <-> quadword in FP registers):
    fp_prologue(g, FPCR_DYN[2])
    for q in ints[:20]:
        v = g.vec([q])
        g.code.append('\tlda\t$1, %s' % v)
        g.code.append('\tldt\t$f1, 0($1)')
        g.code.append('\tcvtlq\t$f1, $f3')
        g.result('$f3', 'cvtlq %016x' % q, fp=True)
        g.code.append('\tcvtql\t$f1, $f3')
        g.result('$f3', 'cvtql %016x' % q, fp=True)
    #  lds/sts round trip (memory format <-> register format):
    for w in (0, 0x80000000, 0x3f800000, 0xbf800000, 0x7f7fffff,
              0x00800000, 0x40490fdb, 0x7f800000, 0xff800000, 0x7fc00000):
        v = g.vec([w | (0xdeadbeef << 32)])
        g.code.append('\tlda\t$1, %s' % v)
        g.code.append('\tlds\t$f1, 0($1)')
        g.result('$f1', 'lds %08x' % w, fp=True)
        g.code.append('\tsts\t$f1, 4($1)')
        g.code.append('\tldq\t$4, 0($1)')
        g.result('$4', 'sts %08x' % w)
    g.code.append('\ttrapb')
    return g


def gen_fp_misc(rng):
    g = Gen('fp_misc')
    vals = [t_bits(x) for x in (0.0, -0.0, 1.0, -1.0, 2.5, -1e300)]
    vals += [rng.getrandbits(64) for _ in range(6)]
    for mnem in ('cpys', 'cpysn', 'cpyse'):
        for a in vals:
            for b in vals[:6]:
                v = g.vec([a, b])
                g.code.append('\tlda\t$1, %s' % v)
                g.code.append('\tldt\t$f1, 0($1)')
                g.code.append('\tldt\t$f2, 8($1)')
                g.code.append('\t%s\t$f1, $f2, $f3' % mnem)
                g.result('$f3', '%s %016x,%016x' % (mnem, a, b), fp=True)
    for mnem in ('fcmoveq', 'fcmovne', 'fcmovlt', 'fcmovge', 'fcmovle',
                 'fcmovgt'):
        for a in vals:
            v = g.vec([a, 0x1111222233334444, 0x5555666677778888])
            g.code.append('\tlda\t$1, %s' % v)
            g.code.append('\tldt\t$f1, 0($1)')
            g.code.append('\tldt\t$f2, 8($1)')
            g.code.append('\tldt\t$f3, 16($1)')
            g.code.append('\t%s\t$f1, $f2, $f3' % mnem)
            g.result('$f3', '%s %016x' % (mnem, a), fp=True)
    for a in vals[:6]:
        v = g.vec([a])
        n = len(g.desc)
        for mnem in ('fbeq', 'fbne', 'fblt', 'fbge', 'fble', 'fbgt'):
            g.code.append('\tlda\t$1, %s' % v)
            g.code.append('\tldt\t$f1, 0($1)')
            g.code.append('\tlda\t$4, 1($31)')
            g.code.append('\t%s\t$f1, fb%d_%s' % (mnem, n, mnem))
            g.code.append('\tlda\t$4, 0($31)')
            g.code.append('fb%d_%s:' % (n, mnem))
            g.result('$4', '%s %016x taken' % (mnem, a))
    #  FPCR: the dynamic rounding mode field reads back.
    for dyn in range(4):
        fp_prologue(g, FPCR_DYN[dyn])
        g.code.append('\tmf_fpcr\t$f3')
        g.code.append('\tstt\t$f3, 0($9)')
        g.code.append('\tldq\t$4, 0($9)')
        g.code.append('\tsrl\t$4, 58, $4')
        g.code.append('\tand\t$4, 3, $4')
        g.result('$4', 'fpcr dyn %d' % dyn)
    fp_prologue(g, FPCR_DYN[2])
    return g


def vax_f_bits(x):
    """VAX F_floating value as held in a register (G-like layout)."""
    if x == 0:
        return 0
    s = 1 if x < 0 else 0
    x = abs(x)
    #  VAX: value = 0.1fff... * 2^(e-128), exponent 8 bits, bias 128.
    import math
    m, e = math.frexp(x)        #  x = m * 2^e, 0.5 <= m < 1
    frac = int(round((m * 2 - 1) * (1 << 23)))
    if frac == 1 << 23:
        frac = 0
        e += 1
    ef = e + 128
    #  Register format: sign<63>, exp<62:52> (11 bits, mapped), frac<51:29>
    if ef & 0x80:
        eg = 0x400 | (ef & 0x7f)
    else:
        eg = ef & 0x7f
        if ef != 0:
            eg |= 0x380
    return (s << 63) | (eg << 52) | (frac << 29)


def vax_g_bits(x):
    """VAX G_floating value as held in a register (same as memory, but with
    the 16-bit words swapped back into order)."""
    if x == 0:
        return 0
    import math
    s = 1 if x < 0 else 0
    x = abs(x)
    m, e = math.frexp(x)
    frac = int(round((m * 2 - 1) * (1 << 52)))
    if frac == 1 << 52:
        frac = 0
        e += 1
    eg = e + 1024
    return (s << 63) | (eg << 52) | frac


def vax_d_bits(x):
    """VAX D_floating value as held in a register: 8-bit exponent in
    <62:55>, 55-bit fraction."""
    if x == 0:
        return 0
    import math
    s = 1 if x < 0 else 0
    x = abs(x)
    m, e = math.frexp(x)
    frac = int(round((m * 2 - 1) * (1 << 55)))
    if frac == 1 << 55:
        frac = 0
        e += 1
    return (s << 63) | ((e + 128) << 55) | frac


def gen_fp_vax(rng):
    g = Gen('fp_vax')
    raw = [1.0, -1.0, 2.0, 0.5, 3.0, 10.0, 0.1, 123.456, -98765.25,
           1e10, 1e-10, 1.0 / 3]
    raw += [rng.uniform(-1e6, 1e6) for _ in range(20)]
    for fmt, conv in (('f', vax_f_bits), ('g', vax_g_bits)):
        vals = [conv(x) for x in raw]
        for fn in ('add', 'sub', 'mul', 'div'):
            for q in ('', '/c', '/u', '/uc', '/s', '/sc', '/su', '/suc'):
                mnem = fn + fmt + q
                for _ in range(8):
                    a = rng.choice(vals)
                    b = rng.choice(vals)
                    v = g.vec([a, b])
                    g.code.append('\tlda\t$1, %s' % v)
                    g.code.append('\tldt\t$f1, 0($1)')
                    g.code.append('\tldt\t$f2, 8($1)')
                    g.code.append('\t%s\t$f1, $f2, $f3' % mnem)
                    g.result('$f3', '%s %016x,%016x' % (mnem, a, b),
                             fp=True)
    gv = [vax_g_bits(x) for x in raw]
    for mnem in ('cmpgeq', 'cmpglt', 'cmpgle'):
        for _ in range(16):
            a = rng.choice(gv)
            b = rng.choice(gv + [a])
            v = g.vec([a, b])
            g.code.append('\tlda\t$1, %s' % v)
            g.code.append('\tldt\t$f1, 0($1)')
            g.code.append('\tldt\t$f2, 8($1)')
            g.code.append('\t%s\t$f1, $f2, $f3' % mnem)
            g.result('$f3', '%s %016x,%016x' % (mnem, a, b), fp=True)
    for mnem in ('cvtgf', 'cvtgf/c', 'cvtgq', 'cvtgq/c', 'cvtgq/v'):
        for a in gv:
            v = g.vec([a])
            g.code.append('\tlda\t$1, %s' % v)
            g.code.append('\tldt\t$f1, 0($1)')
            g.code.append('\t%s\t$f1, $f3' % mnem)
            g.result('$f3', '%s %016x' % (mnem, a), fp=True)
    for mnem in ('cvtqf', 'cvtqf/c', 'cvtqg', 'cvtqg/c'):
        for q in (0, 1, 2, 3, 100, MASK64, 0x7fffffff, 1 << 40,
                  (1 << 60) + 12345, 0x8000000000000000):
            v = g.vec([q])
            g.code.append('\tlda\t$1, %s' % v)
            g.code.append('\tldt\t$f1, 0($1)')
            g.code.append('\t%s\t$f1, $f3' % mnem)
            g.result('$f3', '%s %016x' % (mnem, q), fp=True)
    #  D_floating (QEMU doesn't have it, so these come last and only the
    #  model is used as reference):
    for a in gv:
        v = g.vec([a])
        g.code.append('\tlda\t$1, %s' % v)
        g.code.append('\tldt\t$f1, 0($1)')
        g.code.append('\tcvtgd\t$f1, $f3')
        g.result('$f3', 'cvtgd %016x' % a, fp=True)
    dv = [vax_d_bits(x) for x in raw]
    dv += [vax_d_bits(1.0) | 0x7f, vax_d_bits(1.0) | 0x80,
           vax_d_bits(1.0) | 0xff, vax_d_bits(-3.0) | 0x3ff]
    for mnem in ('cvtdg', 'cvtdg/c'):
        for a in dv:
            v = g.vec([a])
            g.code.append('\tlda\t$1, %s' % v)
            g.code.append('\tldt\t$f1, 0($1)')
            g.code.append('\t%s\t$f1, $f3' % mnem)
            g.result('$f3', '%s %016x' % (mnem, a), fp=True)
    #  ldf/stf and ldg/stg memory formats:
    for x in raw[:8]:
        fb = vax_f_bits(x)
        gb = vax_g_bits(x)
        v = g.vec([fb, gb])
        g.code.append('\tlda\t$1, %s' % v)
        g.code.append('\tldt\t$f1, 0($1)')
        g.code.append('\tldt\t$f2, 8($1)')
        g.code.append('\tstf\t$f1, 0($1)')
        g.code.append('\tstg\t$f2, 8($1)')
        g.code.append('\tldq\t$4, 0($1)')
        g.result('$4', 'stf %016x' % fb)
        g.code.append('\tldq\t$4, 8($1)')
        g.result('$4', 'stg %016x' % gb)
        g.code.append('\tldf\t$f3, 0($1)')
        g.result('$f3', 'ldf (stf %016x)' % fb, fp=True)
        g.code.append('\tldg\t$f3, 8($1)')
        g.result('$f3', 'ldg (stg %016x)' % gb, fp=True)
    g.code.append('\ttrapb')
    return g


