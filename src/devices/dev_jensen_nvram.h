/*
 *  Factory NVRAM contents for the DECpc AXP 150 Flash ROM (ARC 3.0.g).
 *
 *  Captured from the emulated machine after setting it up from an
 *  unconfigured Flash the way an owner would: in the ARC console
 *  "Set default environment variables" (system partition
 *  scsi(0)disk(0)rdisk(0)partition(1)), "Set default configuration"
 *  (3.5" 1.44 MB floppy, no second floppy, U.S. keyboard), and then
 *  "Run EISA configuration utility from floppy" with the Digital ECU
 *  V1.8 for Windows NT diskette, saving the detected configuration
 *  (DEC2400 system board, Adaptec AHA-1742A in slot 1 on IRQ 14).
 *
 *  Block 6 (0x60000) holds firmware data, block C (0xc0000) the ARC
 *  configuration tree, environment variables and the EISA configuration,
 *  including the port initialization the firmware performs at boot (for
 *  example AHA-1742A INTDEF = 0x15: interrupts enabled, IRQ 14).
 *  The rest of both blocks is erased (0xff).
 */

